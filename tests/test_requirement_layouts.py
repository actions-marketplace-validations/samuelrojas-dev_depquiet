"""Projects that keep requirement files instead of a lockfile.

ansible/awx and apache/superset keep compiled files under ``requirements/``,
and home-assistant/core has a pinned ``requirements.txt`` pip cannot resolve
in a clean environment. None of them could be scanned: only a root
``requirements.txt`` was looked for, and a failed resolution ended the scan.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path
from typing import Any
from unittest.mock import patch

import pytest

from depquiet.parsers.pip import PipAuditParser
from depquiet.scanners import (
    ScanError,
    is_compiled_requirements,
    is_tooling_requirements,
    pinned_requirements,
    requirement_files,
    run_pip_audit,
)


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


COMPILED = """\
# This file was autogenerated by uv via the following command:
#    uv pip compile requirements/base.in -o requirements/base.txt
-e ./local-core
    # via app (pyproject.toml)
alembic==1.15.2
    # via flask-migrate
Flask_Migrate[extra]==4.0.7 ; python_version >= "3.9" \\
    --hash=sha256:aaaa \\
    --hash=sha256:bbbb
    # via -r requirements/base.in
"""


class _FakePipAudit:
    """Records each pip-audit call and the requirements it was pointed at."""

    def __init__(self, fail_on: tuple[str, ...] = ()) -> None:
        self.calls: list[dict[str, Any]] = []
        self.fail_on = fail_on

    def __call__(self, cmd: list[str], **kwargs: Any) -> subprocess.CompletedProcess[str]:
        target = Path(cmd[cmd.index("-r") + 1]) if "-r" in cmd else Path(cmd[1])
        pins = target.read_text(encoding="utf-8").split() if target.is_file() else []
        self.calls.append({"target": target, "no_deps": "--no-deps" in cmd, "lines": pins})
        if target.name in self.fail_on and "--no-deps" not in cmd:
            return subprocess.CompletedProcess(cmd, 2, "", "ResolutionImpossible")
        deps = [
            {"name": p.split("==")[0], "version": p.split("==")[1], "vulns": []}
            for p in pins
            if "==" in p
        ]
        Path(cmd[cmd.index("-o") + 1]).write_text(json.dumps({"dependencies": deps}))
        return subprocess.CompletedProcess(cmd, 0, "", "")


def _run(project: Path, fake: _FakePipAudit) -> dict[str, Any]:
    with (
        patch("depquiet.scanners.shutil.which", return_value="/usr/bin/pip-audit"),
        patch("depquiet.scanners.subprocess.run", side_effect=fake),
    ):
        return run_pip_audit(project)


# -- reading ----------------------------------------------------------------


def test_compiled_file_pins(tmp_path: Path) -> None:
    path = _write(tmp_path / "requirements/base.txt", COMPILED)
    assert is_compiled_requirements(path)
    pins, includes = pinned_requirements(path) or ([], [])
    assert pins == ["alembic==1.15.2", "flask-migrate==4.0.7"]
    assert includes == []


@pytest.mark.parametrize(
    "line", ["django>=4", "django", "django==4.*", "django~=4.2", "--no-deps", "django==4.2,<5"]
)
def test_anything_but_exact_pins_is_not_a_pinned_file(tmp_path: Path, line: str) -> None:
    path = _write(tmp_path / "requirements.txt", f"requests==2.0\n{line}\n")
    assert pinned_requirements(path) is None


def test_includes_and_neutral_options(tmp_path: Path) -> None:
    path = _write(
        tmp_path / "requirements/prod.txt",
        "-r base.txt\n-c ../constraints.txt\n--index-url https://example.invalid/simple\n"
        "gunicorn==22.0  # server\ntool @ https://example.invalid/tool.whl\n",
    )
    pins, includes = pinned_requirements(path) or ([], [])
    assert pins == ["gunicorn==22.0"]
    assert includes == [(tmp_path / "requirements/base.txt").resolve()]


@pytest.mark.parametrize(
    ("name", "tooling"),
    [
        ("requirements-dev.txt", True),
        ("requirements_test.txt", True),
        ("requirements_test_pre_commit.txt", True),
        ("development.txt", True),
        ("docs.txt", True),
        ("requirements.txt", False),
        ("base.txt", False),
        ("production.txt", False),
        ("requirements-freqai.txt", False),
        ("devices.txt", False),
    ],
)
def test_tooling_file_names(name: str, tooling: bool) -> None:
    assert is_tooling_requirements(Path(name)) is tooling


def test_requirements_directory_is_detected(tmp_path: Path) -> None:
    assert not PipAuditParser.detect(tmp_path)
    _write(tmp_path / "requirements/base.txt", COMPILED)
    assert PipAuditParser.detect(tmp_path)
    _write(tmp_path / "requirements.txt", "-r requirements/base.txt\n")
    assert [p.name for p in requirement_files(tmp_path)] == ["requirements.txt", "base.txt"]


# -- auditing ---------------------------------------------------------------


def test_compiled_files_are_audited_as_written(tmp_path: Path) -> None:
    """The awx / superset layout: nothing at the root, compiled files in a folder."""
    _write(tmp_path / "pyproject.toml", "[tool.black]\nline-length = 100\n")
    _write(tmp_path / "requirements/base.txt", COMPILED)
    _write(tmp_path / "requirements/development.txt", "# via x\npytest==8.0\n")
    fake = _FakePipAudit()
    report = _run(tmp_path, fake)
    assert len(fake.calls) == 1 and fake.calls[0]["no_deps"]
    assert fake.calls[0]["lines"] == ["alembic==1.15.2", "flask-migrate==4.0.7"]
    assert [d["name"] for d in report["dependencies"]] == ["alembic", "flask-migrate"]
    assert report["depquiet_notes"] == [
        "Development requirement files were not audited: requirements/development.txt."
    ]


def test_hand_pinned_root_file_is_still_resolved(tmp_path: Path) -> None:
    """``django==4.2`` alone says nothing about sqlparse; pip has to resolve it."""
    root = _write(tmp_path / "requirements.txt", "django==4.2\n")
    fake = _FakePipAudit()
    report = _run(tmp_path, fake)
    assert [(c["target"], c["no_deps"]) for c in fake.calls] == [(root, False)]
    assert "depquiet_notes" not in report


def test_unresolvable_pinned_file_falls_back_to_its_pins(tmp_path: Path) -> None:
    """home-assistant: pinned, with a constraints file, and pip cannot resolve it."""
    _write(tmp_path / "requirements.txt", "-c constraints.txt\naiodns==4.0.4\naiohttp==3.14.5\n")
    fake = _FakePipAudit(fail_on=("requirements.txt",))
    report = _run(tmp_path, fake)
    assert [c["no_deps"] for c in fake.calls] == [False, True]
    assert fake.calls[1]["lines"] == ["aiodns==4.0.4", "aiohttp==3.14.5"]
    assert [d["name"] for d in report["dependencies"]] == ["aiodns", "aiohttp"]
    [note] = report["depquiet_notes"]
    assert "could not resolve requirements.txt" in note and "2 pinned versions" in note


def test_unresolvable_unpinned_file_is_an_error(tmp_path: Path) -> None:
    _write(tmp_path / "requirements.txt", "django>=4\n")
    with pytest.raises(ScanError, match="ResolutionImpossible"):
        _run(tmp_path, _FakePipAudit(fail_on=("requirements.txt",)))


def test_only_a_development_file_is_audited_rather_than_nothing(tmp_path: Path) -> None:
    dev = _write(tmp_path / "requirements_dev.txt", "pytest>=8\n")
    fake = _FakePipAudit()
    report = _run(tmp_path, fake)
    assert [(c["target"], c["no_deps"]) for c in fake.calls] == [(dev, False)]
    assert "depquiet_notes" not in report


def test_secondary_files_pinned_or_not(tmp_path: Path) -> None:
    root = _write(tmp_path / "requirements.txt", "django>=4\n")
    _write(tmp_path / "requirements-extra.txt", "-r requirements.txt\ntorch==2.0\n")
    _write(tmp_path / "requirements-plot.txt", "plotly>=5\n")
    fake = _FakePipAudit()
    report = _run(tmp_path, fake)
    assert {(c["target"].name if not c["no_deps"] else "pins") for c in fake.calls} == {
        "pins",
        root.name,
    }
    assert next(c for c in fake.calls if c["no_deps"])["lines"] == ["torch==2.0"]
    notes = " ".join(report["depquiet_notes"])
    assert "requirements-extra.txt" in notes and "were not resolved" in notes
    assert "Not audited, because not fully pinned: requirements-plot.txt." in notes


def test_lockfile_still_wins_over_requirement_files(tmp_path: Path) -> None:
    _write(tmp_path / "requirements.txt", "django>=4\n")
    _write(
        tmp_path / "uv.lock",
        'version = 1\n\n[[package]]\nname = "flask"\nversion = "3.0"\n'
        'source = { registry = "https://pypi.org/simple" }\n',
    )
    fake = _FakePipAudit()
    _run(tmp_path, fake)
    assert [c["lines"] for c in fake.calls] == [["flask==3.0"]]


def test_fallback_audits_the_pins_and_names_the_ranges(tmp_path: Path) -> None:
    """home-assistant/core: mostly pinned, a few ``>=`` lines, unresolvable here."""
    _write(tmp_path / "requirements.txt", "aiohttp==3.14.5\ncertifi>=2021.5.30\nurllib3>=2.0,<3\n")
    fake = _FakePipAudit(fail_on=("requirements.txt",))
    report = _run(tmp_path, fake)
    assert fake.calls[1]["lines"] == ["aiohttp==3.14.5"]
    [note] = report["depquiet_notes"]
    assert "1 pinned versions" in note
    assert "having no exact version: certifi, urllib3." in note
