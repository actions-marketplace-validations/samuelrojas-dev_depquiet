class TestParseOsvResponse:
    def test_basic_response(self) -> None:
        packages = [("lodash", "4.17.20", "npm")]
        response = {
            "results": [
                {
                    "vulns": [
                        {
                            "id": "GHSA-jf85-cpcp-j695",
                            "aliases": ["CVE-2021-23337"],
                            "summary": "Command Injection in lodash",
                            "severity": [{"score": "7.2"}],
                            "affected": [
                                {
                                    "package": {"name": "lodash"},
                                    "ranges": [
                                        {
                                            "events": [
                                                {"introduced": "0"},
                                                {"fixed": "4.17.21"},
                                            ]
                                        }
                                    ],
                                }
                            ],
                            "references": [
                                {
                                    "type": "ADVISORY",
                                    "url": "https://nvd.nist.gov/vuln/detail/CVE-2021-23337",
                                }
                            ],
                        }
                    ]
                }
            ]
        }
        vulns = parse_osv_response(response, packages)
        assert len(vulns) == 1
        v = vulns[0]
        assert v.cve == "CVE-2021-23337"
        assert v.package == "lodash"
        assert v.version == "4.17.20"
        assert v.severity == Severity.HIGH
        assert v.fix_version == "4.17.21"
        assert "nvd.nist.gov" in v.url

    def test_no_cve_alias_uses_osv_id(self) -> None:
        packages = [("pkg", "1.0.0", "npm")]
        response = {
            "results": [
                {
                    "vulns": [
                        {
                            "id": "GHSA-abcd-efgh-ijkl",
                            "aliases": [],
                            "summary": "Some vuln",
                        }
                    ]
                }
            ]
        }
        vulns = parse_osv_response(response, packages)
        assert vulns[0].cve == "GHSA-abcd-efgh-ijkl"

    def test_dedup_same_cve_same_package(self) -> None:
        packages = [("lodash", "4.17.20", "npm")]
        response = {
            "results": [
                {
                    "vulns": [
                        {"id": "GHSA-1", "aliases": ["CVE-2021-1"], "summary": "a"},
                        {"id": "GHSA-2", "aliases": ["CVE-2021-1"], "summary": "b"},
                    ]
                }
            ]
        }
        vulns = parse_osv_response(response, packages)
        assert len(vulns) == 1

    def test_empty_results(self) -> None:
        packages = [("lodash", "4.17.21", "npm")]
        response = {"results": [{"vulns": []}]}
        vulns = parse_osv_response(response, packages)
        assert vulns == []

    def test_no_vulns_key(self) -> None:
        packages = [("lodash", "4.17.21", "npm")]
        response = {"results": [{}]}
        vulns = parse_osv_response(response, packages)
        assert vulns == []

    def test_multiple_packages(self) -> None:
        packages = [
            ("lodash", "4.17.20", "npm"),
            ("express", "4.17.0", "npm"),
        ]
        response = {
            "results": [
                {
                    "vulns": [
                        {"id": "CVE-2021-1", "summary": "lodash vuln"},
                    ]
                },
                {
                    "vulns": [
                        {"id": "CVE-2022-1", "summary": "express vuln"},
                    ]
                },
            ]
        }
        vulns = parse_osv_response(response, packages)
        assert len(vulns) == 2
        assert vulns[0].package == "lodash"
        assert vulns[1].package == "express"


