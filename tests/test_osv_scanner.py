class TestParseLockfiles:
    def test_merges_ecosystems(self, tmp_path: Path) -> None:
        (tmp_path / "package-lock.json").write_text(
            json.dumps(
                {
                    "packages": {
                        "": {},
                        "node_modules/lodash": {"version": "4.17.21"},
                    }
                }
            )
        )
        (tmp_path / "requirements.txt").write_text("requests==2.31.0\n")
        pkgs = parse_lockfiles(tmp_path)
        assert len(pkgs) == 2
        ecosystems = {p[2] for p in pkgs}
        assert ecosystems == {"npm", "PyPI"}

    def test_dedup_across_lockfiles(self, tmp_path: Path) -> None:
        """Same package from different lockfiles is deduplicated by ecosystem:name@version."""
        (tmp_path / "requirements.txt").write_text("flask==3.0.0\n")
        (tmp_path / "Pipfile.lock").write_text(
            json.dumps({"default": {"flask": {"version": "==3.0.0"}}, "develop": {}})
        )
        pkgs = parse_lockfiles(tmp_path)
        assert len(pkgs) == 1

    def test_malformed_lockfile_skipped(self, tmp_path: Path) -> None:
        (tmp_path / "package-lock.json").write_text("not json")
        (tmp_path / "requirements.txt").write_text("flask==3.0.0\n")
        pkgs = parse_lockfiles(tmp_path)
        assert len(pkgs) == 1


