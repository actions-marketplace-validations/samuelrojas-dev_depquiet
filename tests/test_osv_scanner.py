class TestOsvScanner:
    def test_detect_with_lockfile(self, tmp_path: Path) -> None:
        (tmp_path / "package-lock.json").write_text("{}")
        assert OsvScanner.detect(tmp_path) is True

    def test_detect_without_lockfile(self, tmp_path: Path) -> None:
        assert OsvScanner.detect(tmp_path) is False

    def test_parse_returns_empty(self, tmp_path: Path) -> None:
        assert OsvScanner.parse({}, tmp_path) == []

    @patch("depquiet.parsers.osv.query_osv_batch")
    def test_scan_queries_osv(self, mock_query: MagicMock, tmp_path: Path) -> None:
        (tmp_path / "requirements.txt").write_text("flask==3.0.0\nrequests==2.31.0\n")
        mock_query.return_value = {
            "results": [
                {
                    "vulns": [
                        {
                            "id": "GHSA-1234",
                            "aliases": ["CVE-2024-1234"],
                            "summary": "Flask vuln",
                            "severity": [{"score": "7.5"}],
                            "references": [],
                        }
                    ]
                },
                {"vulns": []},
            ]
        }
        vulns = OsvScanner.scan(tmp_path)
        assert len(vulns) == 1
        assert vulns[0].cve == "CVE-2024-1234"
        assert vulns[0].package == "flask"
        mock_query.assert_called_once()

    @patch("depquiet.parsers.osv.query_osv_batch")
    def test_scan_no_lockfiles(self, mock_query: MagicMock, tmp_path: Path) -> None:
        vulns = OsvScanner.scan(tmp_path)
        assert vulns == []
        mock_query.assert_not_called()

    @patch("depquiet.parsers.osv.query_osv_batch")
    def test_scan_network_failure_returns_empty(
        self, mock_query: MagicMock, tmp_path: Path
    ) -> None:
        (tmp_path / "requirements.txt").write_text("flask==3.0.0\n")
        mock_query.side_effect = OSError("Network unreachable")
        vulns = OsvScanner.scan(tmp_path)
        assert vulns == []

    @patch("depquiet.parsers.osv.query_osv_batch")
    def test_scan_batches_large_projects(self, mock_query: MagicMock, tmp_path: Path) -> None:
        """Projects with >1000 packages get batched into multiple API calls."""
        lines = [f"pkg{i}=={i}.0.0" for i in range(1500)]
        (tmp_path / "requirements.txt").write_text("\n".join(lines))
        mock_query.return_value = {"results": [{"vulns": []} for _ in range(1000)]}
        OsvScanner.scan(tmp_path)
        assert mock_query.call_count == 2


