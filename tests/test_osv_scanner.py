class TestEngineOsvIntegration:
    """Test that engine.scan falls back to OSV when no scanner is detected."""

    @patch("depquiet.engine.OsvScanner.scan")
    @patch("depquiet.engine.OsvScanner.detect", return_value=True)
    def test_osv_fallback(
        self, mock_detect: MagicMock, mock_scan: MagicMock, tmp_path: Path
    ) -> None:
        """When no audit JSON and no native scanner, use OSV if lockfiles exist."""
        mock_scan.return_value = [
            Vulnerability(
                cve="CVE-2024-1234",
                package="serde",
                version="1.0.0",
                severity=Severity.HIGH,
                title="Serde vuln",
            )
        ]
        from depquiet.engine import scan as engine_scan

        result = engine_scan(project=tmp_path, skip_epss=False)
        mock_scan.assert_called_once_with(tmp_path)
        assert len(result.results) == 1
        assert result.package_manager == "osv"

    @patch("depquiet.engine.OsvScanner.detect", return_value=True)
    def test_osv_skipped_when_offline(self, mock_detect: MagicMock, tmp_path: Path) -> None:
        """OSV is skipped when skip_epss=True (offline mode)."""
        from depquiet.engine import scan as engine_scan

        result = engine_scan(project=tmp_path, skip_epss=True)
        assert result.results == []

    @patch("depquiet.engine.OsvScanner.scan")
    def test_native_scanner_takes_priority(self, mock_osv: MagicMock, tmp_path: Path) -> None:
        """When a native scanner is detected, OSV is not used."""
        (tmp_path / "package-lock.json").write_text(json.dumps({"packages": {}}))
        from depquiet.engine import scan as engine_scan

        engine_scan(project=tmp_path, skip_epss=True)
        mock_osv.assert_not_called()
