class TestParsePackageLock:
    def test_v2_format(self, tmp_path: Path) -> None:
        data = {
            "packages": {
                "": {"name": "my-app", "version": "1.0.0"},
                "node_modules/lodash": {"version": "4.17.21"},
                "node_modules/@babel/core": {
                    "name": "@babel/core",
                    "version": "7.24.0",
                },
            }
        }
        p = tmp_path / "package-lock.json"
        p.write_text(json.dumps(data))
        result = _parse_package_lock(p)
        assert len(result) == 2
        names = {r[0] for r in result}
        assert "lodash" in names
        assert "@babel/core" in names
        assert all(r[2] == "npm" for r in result)

    def test_v1_format(self, tmp_path: Path) -> None:
        data = {
            "dependencies": {
                "express": {"version": "4.18.2"},
                "cors": {"version": "2.8.5"},
            }
        }
        p = tmp_path / "package-lock.json"
        p.write_text(json.dumps(data))
        result = _parse_package_lock(p)
        assert len(result) == 2

    def test_dedup(self, tmp_path: Path) -> None:
        data = {
            "packages": {
                "": {},
                "node_modules/lodash": {"version": "4.17.21"},
                "node_modules/sub/node_modules/lodash": {
                    "name": "lodash",
                    "version": "4.17.21",
                },
            }
        }
        p = tmp_path / "package-lock.json"
        p.write_text(json.dumps(data))
        result = _parse_package_lock(p)
        assert len(result) == 1

    def test_empty_root_skipped(self, tmp_path: Path) -> None:
        data = {"packages": {"": {"name": "root", "version": "1.0.0"}}}
        p = tmp_path / "package-lock.json"
        p.write_text(json.dumps(data))
        result = _parse_package_lock(p)
        assert result == []


