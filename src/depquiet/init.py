"""``depquiet init`` — interactive config scaffolder.

Detects the project environment (package manager, CI provider, existing
scanners / SBOM tools) and generates a ``.depquiet.yaml`` with sensible
defaults.  Supports a ``--yes`` non-interactive mode for scripted setups.

Detection signals
-----------------
* **Package manager**: package.json, requirements.txt / pyproject.toml / Pipfile,
  go.mod, Cargo.toml, pom.xml / build.gradle, *.gemspec / Gemfile,
  composer.json, pubspec.yaml, *.csproj / *.sln.
* **CI provider**: .github/workflows/, .gitlab-ci.yml, Jenkinsfile,
  .circleci/config.yml, bitbucket-pipelines.yml, azure-pipelines.yml.
* **Existing scanners**: .snyk, trivy.yaml, .grype.yaml, .osv-scanner.toml,
  dependabot.yml.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass, field
from pathlib import Path
from textwrap import dedent

# ---------------------------------------------------------------------------
# Detection dataclasses
# ---------------------------------------------------------------------------


@dataclass
class ProjectInfo:
    """Detected project characteristics."""

    package_managers: list[str] = field(default_factory=list)
    ci_providers: list[str] = field(default_factory=list)
    existing_scanners: list[str] = field(default_factory=list)
    has_depquiet_config: bool = False


# ---------------------------------------------------------------------------
# Detection helpers
# ---------------------------------------------------------------------------

_PM_SIGNALS: list[tuple[str, list[str]]] = [
    ("npm", ["package.json"]),
    ("pip", ["requirements.txt", "pyproject.toml", "Pipfile", "setup.py", "setup.cfg"]),
    ("go", ["go.mod"]),
    ("cargo", ["Cargo.toml"]),
    ("maven", ["pom.xml"]),
    ("gradle", ["build.gradle", "build.gradle.kts"]),
    ("gem", ["Gemfile", "*.gemspec"]),
    ("composer", ["composer.json"]),
    ("pub", ["pubspec.yaml"]),
    ("nuget", ["*.csproj", "*.sln", "packages.config"]),
]

_CI_SIGNALS: list[tuple[str, list[str]]] = [
    ("github-actions", [".github/workflows"]),
    ("gitlab-ci", [".gitlab-ci.yml"]),
    ("jenkins", ["Jenkinsfile"]),
    ("circleci", [".circleci/config.yml", ".circleci"]),
    ("bitbucket", ["bitbucket-pipelines.yml"]),
    ("azure-devops", ["azure-pipelines.yml"]),
]

_SCANNER_SIGNALS: list[tuple[str, list[str]]] = [
    ("snyk", [".snyk"]),
    ("trivy", ["trivy.yaml", ".trivy.yaml"]),
    ("grype", [".grype.yaml"]),
    ("osv-scanner", [".osv-scanner.toml"]),
    ("dependabot", [".github/dependabot.yml", ".github/dependabot.yaml"]),
    ("renovate", ["renovate.json", ".renovaterc", ".renovaterc.json"]),
]


def _match_signal(project: Path, patterns: list[str]) -> bool:
    """Return True if any of *patterns* exist in *project*.

    Plain names are checked as direct children.  Names with ``*`` are
    expanded via glob.  Names ending with ``/`` or that look like
    directories are checked with ``is_dir()``.
    """
    for pat in patterns:
        if "*" in pat:
            if list(project.glob(pat)):
                return True
        else:
            candidate = project / pat
            if candidate.exists():
                return True
    return False


def detect_project(project: Path) -> ProjectInfo:
    """Detect package managers, CI, and existing scanners in *project*."""
    info = ProjectInfo()

    for name, patterns in _PM_SIGNALS:
        if _match_signal(project, patterns):
            info.package_managers.append(name)

    for name, patterns in _CI_SIGNALS:
        if _match_signal(project, patterns):
            info.ci_providers.append(name)

    for name, patterns in _SCANNER_SIGNALS:
        if _match_signal(project, patterns):
            info.existing_scanners.append(name)

    info.has_depquiet_config = (project / ".depquiet.yaml").is_file() or (
        project / ".depquiet.yml"
    ).is_file()

    return info


# ---------------------------------------------------------------------------
# Config generation
# ---------------------------------------------------------------------------


def _pick_fail_on(info: ProjectInfo) -> str:
    """Pick a default fail_on severity for CI gating."""
    # Start conservative — only block on high+ by default.
    return "high"


def generate_config(
    info: ProjectInfo,
    *,
    sarif: bool = False,
    summary: bool = False,
) -> str:
    """Generate a .depquiet.yaml string based on detected project info."""
    lines: list[str] = []

    # Header
    lines.append("# depquiet configuration")
    lines.append("# Generated by `depquiet init` — edit as needed.")
    lines.append("# Docs: https://github.com/samuelrojas-dev/depquiet#configuration")
    lines.append("")

    # Triage tuning: EPSS orders the report; filtering by it is opt-in
    lines.append("# EPSS orders alerts by exploit probability. To also hide alerts")
    lines.append("# scoring below a cutoff, uncomment (0-1, e.g. 0.05 for 5%):")
    lines.append("# epss_threshold: 0.05")
    lines.append("")

    # CI gate
    fail_on = _pick_fail_on(info)
    lines.append(f"fail_on: {fail_on}")
    lines.append("")

    # KEV — recommend enabling it
    lines.append("# Check CISA Known Exploited Vulnerabilities catalog")
    lines.append("kev: true")
    lines.append("")

    # always_flag — leave empty but show the pattern
    lines.append("# Packages that must never be filtered (always ACTION)")
    lines.append("# always_flag:")
    lines.append("#   - example-critical-package")
    lines.append("")

    # Output files — enable sarif/summary if GitHub Actions detected
    has_gha = "github-actions" in info.ci_providers
    if has_gha or sarif:
        lines.append("# Output files (relative to project root)")
        lines.append("sarif: reports/depquiet.sarif")
        if has_gha or summary:
            lines.append("summary: reports/summary.md")
        lines.append("")

    # Existing scanners note
    if info.existing_scanners:
        scanners = ", ".join(info.existing_scanners)
        lines.append(f"# Detected existing scanners: {scanners}")
        lines.append("# depquiet complements these by triaging their output.")
        lines.append("")

    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Interactive prompts
# ---------------------------------------------------------------------------


def _confirm(prompt: str, default: bool = True) -> bool:
    """Ask a yes/no question on the terminal."""
    suffix = " [Y/n] " if default else " [y/N] "
    try:
        answer = input(prompt + suffix).strip().lower()
    except (EOFError, KeyboardInterrupt):
        print()
        return default
    if not answer:
        return default
    return answer in ("y", "yes")


def _print_detection(info: ProjectInfo) -> None:
    """Print what we detected about the project."""
    if info.package_managers:
        pms = ", ".join(info.package_managers)
        print(f"  Package managers: {pms}")
    else:
        print("  Package managers: (none detected)")

    if info.ci_providers:
        cis = ", ".join(info.ci_providers)
        print(f"  CI providers:     {cis}")

    if info.existing_scanners:
        scanners = ", ".join(info.existing_scanners)
        print(f"  Existing scanners: {scanners}")


# ---------------------------------------------------------------------------
# Main entry point
# ---------------------------------------------------------------------------


def init_command(
    project: Path,
    *,
    yes: bool = False,
    force: bool = False,
    output: Path | None = None,
) -> int:
    """Run the ``depquiet init`` subcommand. Returns exit code.

    Parameters
    ----------
    project:
        Root directory of the project.
    yes:
        Non-interactive mode — accept all defaults.
    force:
        Overwrite existing .depquiet.yaml if present.
    output:
        Write to a custom path instead of ``<project>/.depquiet.yaml``.
    """
    dest = output or (project / ".depquiet.yaml")
    if not project.is_dir():
        # A mistyped --path must not create a new folder with a config in it.
        print(f"Error: project directory not found: {project}", file=sys.stderr)
        return 2

    # Detect project
    info = detect_project(project)

    if not yes:
        print()
        print("depquiet init")
        print("=" * 40)
        print()
        _print_detection(info)
        print()

    # Check for existing config
    if info.has_depquiet_config and not force:
        if yes:
            print(
                "Error: .depquiet.yaml already exists. Use --force to overwrite.",
                file=sys.stderr,
            )
            return 1
        if not _confirm("A .depquiet.yaml already exists. Overwrite?", default=False):
            print("Aborted.")
            return 0

    # Generate config
    config_text = generate_config(info)

    if not yes:
        print("Generated config:")
        print("-" * 40)
        print(config_text)
        if not _confirm("Write this to " + str(dest) + "?"):
            print("Aborted.")
            return 0

    # Write the file
    try:
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(config_text, encoding="utf-8")
    except OSError as exc:
        print(f"Error: could not write {dest}: {exc}", file=sys.stderr)
        return 1

    if not yes:
        print()
    print(f"Wrote {dest}")

    # Suggest next steps
    if not yes:
        print()
        print("Next steps:")
        print(f"  1. Review and customize {dest.name}")
        print("  2. Run `depquiet` to scan your project")
        if "github-actions" in info.ci_providers:
            print("  3. Add depquiet to your CI pipeline:")
            print(
                dedent("""\
                     - name: Triage vulnerabilities
                       run: depquiet --json > results.json
                """).rstrip()
            )
        print()

    return 0
