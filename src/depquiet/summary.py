"""GitHub-flavored Markdown summary — for $GITHUB_STEP_SUMMARY and --summary.

Renders a rich Markdown report that GitHub Actions displays directly in
the PR checks page. This is the first thing a security team sees when
evaluating depquiet in CI, so it needs to look polished.
"""

from __future__ import annotations

from pathlib import Path

from depquiet.models import FilterReason, ScanResult


def render_summary(result: ScanResult) -> str:
    """Return a complete GFM summary of the scan result."""
    lines: list[str] = []

    total = len(result.results)
    action_count = len(result.action)
    review_count = len(result.review)
    filtered_count = len(result.filtered)
    filter_rate = result.filter_rate

    # Title with status badge
    if action_count == 0:
        lines.append("## ✅ depquiet — All clear")
    else:
        lines.append(f"## 🔴 depquiet — {action_count} action required")

    lines.append("")

    # Stats bar
    lines.append(
        f"**{total}** alerts scanned · "
        f"**{filtered_count}** filtered ({filter_rate:.0f}%) · "
        f"**{review_count}** review · "
        f"**{action_count}** action"
    )
    lines.append("")

    if not result.results:
        lines.append("No vulnerabilities found. 🎉")
        return "\n".join(lines)

    # Action items table
    if result.action:
        lines.append("### 🔴 Action required")
        lines.append("")
        lines.append("| CVE | Package | Severity | EPSS | Fix |")
        lines.append("|-----|---------|----------|------|-----|")
        for r in result.action:
            epss = f"{r.epss_score:.0%}" if r.epss_score is not None else "—"
            fix = f"`{r.vuln.fix_version}`" if r.vuln.fix_version else "—"
            sev = _severity_badge(r.vuln.severity.value)
            cve = r.vuln.cve
            if r.vuln.url:
                cve = f"[{r.vuln.cve}]({r.vuln.url})"
            lines.append(f"| {cve} | `{r.vuln.package}` | {sev} | {epss} | {fix} |")
        lines.append("")

    # Review items table (collapsed if >5)
    if result.review:
        lines.append("### ⚠️ Review")
        lines.append("")
        if len(result.review) > 5:
            lines.append("<details>")
            lines.append(f"<summary>{len(result.review)} items to review</summary>")
            lines.append("")
        lines.append("| CVE | Package | Severity | EPSS |")
        lines.append("|-----|---------|----------|------|")
        for r in result.review:
            epss = f"{r.epss_score:.0%}" if r.epss_score is not None else "—"
            sev = _severity_badge(r.vuln.severity.value)
            cve = r.vuln.cve
            if r.vuln.url:
                cve = f"[{r.vuln.cve}]({r.vuln.url})"
            lines.append(f"| {cve} | `{r.vuln.package}` | {sev} | {epss} |")
        if len(result.review) > 5:
            lines.append("")
            lines.append("</details>")
        lines.append("")

    # Filtered breakdown (collapsed)
    if result.filtered:
        by_reason: dict[FilterReason, int] = {}
        for r in result.filtered:
            for reason in r.reasons:
                by_reason[reason] = by_reason.get(reason, 0) + 1

        reason_labels = {
            FilterReason.UNREACHABLE: "Unreachable code",
            FilterReason.DEV_DEPENDENCY: "Dev dependency only",
            FilterReason.LOW_EPSS: "Low EPSS score",
            FilterReason.COMMUNITY_TEMPLATE: "Community template match",
            FilterReason.IGNORED: "Suppressed (.depquiet-ignore)",
        }

        lines.append("<details>")
        lines.append(f"<summary>✅ {filtered_count} alerts filtered ({filter_rate:.0f}%)</summary>")
        lines.append("")
        lines.append("| Reason | Count |")
        lines.append("|--------|------:|")
        for reason, count in sorted(by_reason.items(), key=lambda x: -x[1]):
            label = reason_labels.get(reason, reason.value)
            lines.append(f"| {label} | {count} |")
        lines.append("")
        lines.append("</details>")
        lines.append("")

    # Footer
    lines.append("---")
    lines.append(
        f"*Generated by [depquiet](https://github.com/samuelrojas-dev/depquiet) v{_get_version()}*"
    )

    return "\n".join(lines)


def write_summary(result: ScanResult, path: Path) -> None:
    """Write the GFM summary to a file (typically $GITHUB_STEP_SUMMARY)."""
    md = render_summary(result)
    path.write_text(md + "\n", encoding="utf-8")


def _severity_badge(severity: str) -> str:
    """Map severity to a visual badge for markdown tables."""
    badges = {
        "critical": "🟣 Critical",
        "high": "🔴 High",
        "moderate": "🟡 Moderate",
        "low": "🟢 Low",
        "info": "Info",
    }
    return badges.get(severity, severity)


def _get_version() -> str:
    """Get the depquiet version string."""
    try:
        from depquiet import __version__

        return __version__
    except ImportError:
        return "?"
